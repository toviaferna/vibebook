_WORD = re.compile(r"[a-záéíóúüñ]+")
_ACCENTS = set("áéíóúüñ¿¡")


def detect_language(text: str, minimum_tokens: int = 12) -> str | None:
    """Return ``es`` or ``en`` when the sample is clearly one of them.

    It is deliberately conservative: ambiguous or very short samples return
    ``None`` so the caller keeps the EPUB metadata.
    """
    tokens = _WORD.findall(text.casefold())
    if len(tokens) < minimum_tokens:
        return None
    sample = tokens[:6_000]
    total = len(sample)
    spanish = sum(1 for token in sample if token in _SPANISH_WORDS)
    english = sum(1 for token in sample if token in _ENGLISH_WORDS)
    spanish_ratio = spanish / total
    english_ratio = english / total
    accent_bonus = 0.03 if any(character in _ACCENTS for character in text.casefold()) else 0.0

    if spanish_ratio >= 0.02 and spanish_ratio + accent_bonus > english_ratio * 1.25 + 0.005:
        return "es"
    if english_ratio >= 0.02 and english_ratio > (spanish_ratio + accent_bonus) * 1.25 + 0.005:
        return "en"
    return None
